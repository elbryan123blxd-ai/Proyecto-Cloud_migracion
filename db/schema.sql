-- SIMPLIFICADA frente a produccion: ya no pasa por soporte_activo(), porque
-- el modo soporte pertenece al panel de plataforma (fuera de alcance).
create or replace function mi_academia()
returns uuid language sql stable security definer set search_path to 'public' as $$
  select academia_id from public.profiles where id = auth.uid();
$$;

-- SIMPLIFICADA: no hay tabla de suscripciones en este clon, nadie queda
-- cortado por impago a la plataforma.
create or replace function academia_activa()
returns boolean language sql stable security definer set search_path to 'public' as $$
  select true;
$$;

-- SIMPLIFICADA: no hay admins de plataforma en este clon.
create or replace function es_plataforma()
returns boolean language sql stable security definer set search_path to 'public' as $$
  select false;
$$;

create or replace function is_director()
returns boolean language sql stable security definer set search_path to 'public' as $$
  select exists (select 1 from public.profiles p where p.id = auth.uid() and p.rol = 'director');
$$;

create or replace function puede_sede(s text)
returns boolean language sql stable security definer set search_path to 'public' as $$
  select public.is_director()
      or exists (select 1 from public.admin_sedes a where a.profile_id = auth.uid() and a.sede = s);
$$;

create or replace function puede_salon(p_salon_id text)
returns boolean language sql stable security definer set search_path to 'public' as $$
  select exists (
    select 1 from public.salones s
    where s.id = p_salon_id
      and s.academia_id = public.mi_academia()
      and public.puede_sede(s.sede)
  );
$$;

create or replace function puede_alumno(p_student_id text)
returns boolean language sql stable security definer set search_path to 'public' as $$
  select exists (
    select 1 from public.students s
    where s.id = p_student_id
      and s.academia_id = public.mi_academia()
      and public.puede_sede(s.sede)
  );
$$;

create or replace function alumno_moroso(p_student_id text)
returns boolean language sql stable security definer set search_path to 'public' as $$
  select exists (
    select 1 from public.cuotas c
    where c.student_id = p_student_id
      and c.pago_id is null
      and c.vence < ((now() at time zone 'America/Lima')::date - 15)
  );
$$;

create or replace function mi_alumno()
returns text language sql stable security definer set search_path to 'public' as $$
  select s.id from public.students s
  where s.user_id = auth.uid()
    and s.retirado_en is null
    and not public.alumno_moroso(s.id);
$$;

create or replace function mi_personal()
returns text language sql stable security definer set search_path to 'public' as $$
  select id from public.personal
  where user_id = auth.uid() and rol = 'Docente' and estado = 'Activo';
$$;

create or replace function mi_salon()
returns text language sql stable security definer set search_path to 'public' as $$
  select salon_id from public.students where user_id = auth.uid();
$$;

create or replace function mi_tutor()
returns text language sql stable security definer set search_path to 'public' as $$
  select p.id from public.personal p
  where p.user_id = auth.uid()
    and p.estado = 'Activo'
    and exists (
      select 1 from public.salones s
      where s.academia_id = p.academia_id and s.tutor_id = p.id
    );
$$;

create or replace function es_mi_tutorado(p_student_id text)
returns boolean language sql stable security definer set search_path to 'public' as $$
  select exists (
    select 1 from public.students a
    join public.salones s on s.academia_id = a.academia_id and s.id = a.salon_id
    where a.id = p_student_id and s.tutor_id = public.mi_tutor()
  );
$$;

