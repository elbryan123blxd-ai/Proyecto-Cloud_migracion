-- Schema del clon de Academia Premier para AWS.
-- Extraido via MCP de supabase-academia: SOLO estructura (columnas, FKs, RLS,
-- funciones). Ni una fila de dato real toco este archivo.
--
-- Alcance (decidido 2026-10-12): Tutor, Alumno y Profesor funcionan al 100%.
-- El Dashboard (director) funciona salvo facturacion SUNAT, gastos y cierres
-- de caja. El panel del dueno de la plataforma queda fuera a proposito.
--
-- Simplificado a proposito frente a produccion:
--   - mi_academia() ya no pasa por "modo soporte" (soporte_activo()) porque
--     ese modo pertenece al panel de plataforma, que no existe en este clon.
--   - academia_activa() siempre da true: no hay tabla de suscripciones aca,
--     el corte por impago de la plataforma no es parte de esta demo.
--   - es_plataforma() siempre da false: no hay admins de plataforma aca.
--   - answer_sheets / ocr_results NO se portan: son un pipeline de vision
--     por computadora (escaneo de examenes), no infraestructura cloud.
--     exam_results guarda los puntajes ya calculados, como dato generado.
--   - Las FKs compuestas de produccion que atan (academia_id, sede) a
--     sedes(academia_id, nombre) -- una segunda capa de aislamiento por
--     tenant -- se simplifican aca a FKs simples por id. Es una tecnica
--     linda de produccion, pero no hace falta para demostrar el concepto.
--
-- Pensado para correr una sola vez contra Aurora Serverless v2, despues de
-- que exista (Fase 1 de docs/PLAN.md). PostgREST expone esto como API.
-- auth.users lo crea GoTrue solo, no este archivo.

